function t(key) {
  const lang = localStorage.getItem("fs-guide-pro-settings");
  let selected = "ro";
  try { selected = JSON.parse(lang || "{}").language || "ro"; } catch {}
  return translations[selected]?.[key] || translations.ro[key] || key;
}

function setLanguage(lang) {
  const p = getPrefs();
  p.language = lang;
  savePrefs(p);
  renderApp();
}

function tr(key) {
  return t(key);
}
